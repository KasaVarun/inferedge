#!/usr/bin/env python3
"""Write the deterministic dynamic-batch GEMM and its fixtures.

CMake does not run this script. It requires onnx==1.22.0. An optional
argument is the models directory that receives the ONNX file and fixtures.
The default is the directory that contains this script.

The single node is Gemm with transA=0, transB=0, alpha=1, and beta=0.
The weight initializer is not a graph input. There is no bias.
"""

from __future__ import annotations

import sys
from pathlib import Path

import onnx
from onnx import TensorProto, helper

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from weight_rng import (
        FIXTURE_BATCH_SIZES,
        GEMM_INITIALIZER_NAMES,
        SplitMix64,
        assert_finite,
        draw_vector,
        fixture_attempt_ids,
        gemm_row,
        input_matrix,
        manifest_text,
        pack_f32,
        require_onnx_version,
        rows_are_distinct,
    )
else:
    from models.weight_rng import (
        FIXTURE_BATCH_SIZES,
        GEMM_INITIALIZER_NAMES,
        SplitMix64,
        assert_finite,
        draw_vector,
        fixture_attempt_ids,
        gemm_row,
        input_matrix,
        manifest_text,
        pack_f32,
        require_onnx_version,
        rows_are_distinct,
    )

IR_VERSION = 10
OPSET_VERSION = 13
STEM = "gemm_f32"
WIDTH = 512
PARAMETER_COUNT = WIDTH * WIDTH
WEIGHT_BYTES = PARAMETER_COUNT * 4


def draw_weight() -> list[float]:
    weight = draw_vector(SplitMix64(), PARAMETER_COUNT, WIDTH)
    assert_finite(weight, "weight")
    if len(weight) != PARAMETER_COUNT:
        raise SystemExit(f"parameter count is {len(weight)}, expected {PARAMETER_COUNT}")
    return weight


def build_model(weight: list[float]) -> onnx.ModelProto:
    initializer = helper.make_tensor(
        GEMM_INITIALIZER_NAMES[0],
        TensorProto.FLOAT,
        [WIDTH, WIDTH],
        pack_f32(weight),
        raw=True,
    )
    node = helper.make_node(
        "Gemm",
        ["features", "weight"],
        ["product"],
        transA=0,
        transB=0,
        alpha=1.0,
        beta=0.0,
    )
    graph = helper.make_graph(
        [node],
        STEM,
        [helper.make_tensor_value_info("features", TensorProto.FLOAT, ["batch", WIDTH])],
        [helper.make_tensor_value_info("product", TensorProto.FLOAT, ["batch", WIDTH])],
        [initializer],
    )
    model = helper.make_model(
        graph,
        ir_version=IR_VERSION,
        opset_imports=[helper.make_opsetid("", OPSET_VERSION)],
        producer_name="inferedge",
        producer_version="0.1.0",
        doc_string=(
            "Deterministic float32 gemm_f32 graph. "
            "Generated by models/generate_gemm_model.py. "
            f"IR {IR_VERSION}, opset {OPSET_VERSION}."
        ),
    )
    if model.ir_version != IR_VERSION:
        raise SystemExit(f"IR version is {model.ir_version}, expected {IR_VERSION}")
    if len(model.opset_import) != 1 or model.opset_import[0].version != OPSET_VERSION:
        raise SystemExit(f"opset import is not {OPSET_VERSION}")
    if initializer.data_location != TensorProto.DEFAULT or initializer.external_data:
        raise SystemExit("weight initializer is not embedded")
    onnx.checker.check_model(model)
    return model


def build_artifacts() -> dict[str, bytes]:
    weight = draw_weight()
    model = build_model(weight)
    files = {
        f"{STEM}.onnx": model.SerializeToString(),
        f"fixtures/{STEM}.weights": pack_f32(weight),
        f"fixtures/{STEM}/manifest.txt": manifest_text(STEM, WIDTH, WIDTH).encode("ascii"),
    }
    for batch_size in FIXTURE_BATCH_SIZES:
        attempt_ids = fixture_attempt_ids(batch_size)
        inputs = input_matrix(attempt_ids, WIDTH)
        if not rows_are_distinct(inputs):
            raise SystemExit(f"batch {batch_size} input rows are not distinct")
        outputs = []
        for row in inputs:
            result = gemm_row(row, weight, WIDTH, WIDTH)
            assert_finite(result, "product")
            outputs.append(result)
        tag = f"b{batch_size:02d}"
        files[f"fixtures/{STEM}/{tag}.input.f32"] = b"".join(pack_f32(row) for row in inputs)
        files[f"fixtures/{STEM}/{tag}.expected.f32"] = b"".join(pack_f32(row) for row in outputs)
    return files


def write_artifacts(models_dir: Path, files: dict[str, bytes]) -> None:
    root = models_dir.resolve()
    for relative, payload in files.items():
        destination = (root / relative).resolve()
        if destination != root and root not in destination.parents:
            raise SystemExit(f"refusing to write outside {root}: {relative}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(payload)


def main() -> None:
    require_onnx_version(onnx.__version__)
    if len(sys.argv) > 2:
        raise SystemExit("usage: generate_gemm_model.py [models-directory]")
    models_dir = Path(sys.argv[1]) if len(sys.argv) == 2 else Path(__file__).resolve().parent
    write_artifacts(models_dir, build_artifacts())
    sidecar = models_dir / "fixtures" / f"{STEM}.weights"
    if sidecar.stat().st_size != WEIGHT_BYTES:
        raise SystemExit(f"weight sidecar is {sidecar.stat().st_size} bytes, expected {WEIGHT_BYTES}")


if __name__ == "__main__":
    main()

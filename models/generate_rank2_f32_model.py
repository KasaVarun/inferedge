#!/usr/bin/env python3
"""Write models/rank2_f32.onnx, a deterministic float32[1, 2] Identity graph.

The script is a developer tool. CMake does not run it. Install the pin in
models/requirements.txt into a virtual environment before regenerating the
committed model, then update the SHA-256 in CMakeLists.txt.

The CLI refuses this fixture because its input is not a fixed rank-1 tensor.
"""

from pathlib import Path

import onnx
from onnx import TensorProto, helper

REQUIRED_ONNX_VERSION = "1.22.0"
IR_VERSION = 10
OPSET_VERSION = 13


def main() -> None:
    if onnx.__version__ != REQUIRED_ONNX_VERSION:
        raise SystemExit(
            f"onnx {REQUIRED_ONNX_VERSION} is required, found {onnx.__version__}"
        )

    input_m = helper.make_tensor_value_info("M", TensorProto.FLOAT, [1, 2])
    output_n = helper.make_tensor_value_info("N", TensorProto.FLOAT, [1, 2])
    node = helper.make_node("Identity", ["M"], ["N"])
    graph = helper.make_graph([node], "rank2_f32", [input_m], [output_n])
    model = helper.make_model(
        graph,
        ir_version=IR_VERSION,
        opset_imports=[helper.make_opsetid("", OPSET_VERSION)],
        producer_name="inferedge",
        producer_version="0.1.0",
        doc_string=(
            "Deterministic float32[1, 2] Identity fixture. "
            "Generated by models/generate_rank2_f32_model.py. IR 10, opset 13."
        ),
    )
    if model.ir_version != IR_VERSION:
        raise SystemExit(f"IR version is {model.ir_version}, expected {IR_VERSION}")
    if len(model.opset_import) != 1 or model.opset_import[0].version != OPSET_VERSION:
        raise SystemExit(f"opset import is not {OPSET_VERSION}")

    onnx.checker.check_model(model)
    destination = Path(__file__).resolve().parent / "rank2_f32.onnx"
    onnx.save(model, destination)


if __name__ == "__main__":
    main()

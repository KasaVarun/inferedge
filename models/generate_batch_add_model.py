#!/usr/bin/env python3
"""Write models/batch_add_f32.onnx, a deterministic float32 Add graph.

The graph adds two rank-2 inputs. Axis 0 is the symbolic dimension "batch".
Axis 1 is the static feature size 2. The script is a developer tool. CMake
does not run it. Install the pin in models/requirements.txt into a virtual
environment before regenerating the committed model, then update the SHA-256
in CMakeLists.txt.

An optional first argument selects the output path. The default is
models/batch_add_f32.onnx next to this script.
"""

import sys
from pathlib import Path

import onnx
from onnx import TensorProto, helper

REQUIRED_ONNX_VERSION = "1.22.0"
IR_VERSION = 10
OPSET_VERSION = 13
BATCH_DIM = "batch"


def main() -> None:
    if onnx.__version__ != REQUIRED_ONNX_VERSION:
        raise SystemExit(
            f"onnx {REQUIRED_ONNX_VERSION} is required, found {onnx.__version__}"
        )

    shape = [BATCH_DIM, 2]
    input_a = helper.make_tensor_value_info("A", TensorProto.FLOAT, shape)
    input_b = helper.make_tensor_value_info("B", TensorProto.FLOAT, shape)
    output_c = helper.make_tensor_value_info("C", TensorProto.FLOAT, shape)
    node = helper.make_node("Add", ["A", "B"], ["C"])
    graph = helper.make_graph(
        [node],
        "batch_add_f32",
        [input_a, input_b],
        [output_c],
    )
    model = helper.make_model(
        graph,
        ir_version=IR_VERSION,
        opset_imports=[helper.make_opsetid("", OPSET_VERSION)],
        producer_name="inferedge",
        producer_version="0.1.0",
        doc_string=(
            "Deterministic float32[batch, 2] Add fixture. "
            "Generated by models/generate_batch_add_model.py. IR 10, opset 13."
        ),
    )
    if model.ir_version != IR_VERSION:
        raise SystemExit(f"IR version is {model.ir_version}, expected {IR_VERSION}")
    if len(model.opset_import) != 1 or model.opset_import[0].version != OPSET_VERSION:
        raise SystemExit(f"opset import is not {OPSET_VERSION}")

    onnx.checker.check_model(model)
    if len(sys.argv) > 2:
        raise SystemExit("usage: generate_batch_add_model.py [output.onnx]")
    destination = (
        Path(sys.argv[1])
        if len(sys.argv) == 2
        else Path(__file__).resolve().parent / "batch_add_f32.onnx"
    )
    onnx.save(model, destination)


if __name__ == "__main__":
    main()
